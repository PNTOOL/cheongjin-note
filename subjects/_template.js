/* 하랑노트 새 과목 양식 (예시)
 *
 * 이 파일을 복사해서 새 과목 파일을 만들어요. 예: subjects/pathophysiology-1.js
 *   1) 아래 id, title을 새 과목에 맞게 바꿔요. id는 영어 소문자와 - 만 쓰고, list.js의 id와 똑같이 써요.
 *   2) units(단원) 안에 concepts(개념)와 qs(문제)를 채워요.
 *   3) subjects/list.js에 과목을 한 줄 추가하면 첫 화면에 나와요.
 *
 * 개념 하나의 항목
 *   id   바꾸면 안 되는 고유 이름 (예: 'u1c01' = 1단원 1번 개념). 학습 기록이 이 이름으로 저장돼요.
 *   t    제목
 *   pr   시험 중요도: 3 = ★★★ 자주 출제 (당일치기), 2 = ★★ 중요, 1 = ★ 기본
 *   ex   설명 (\n 으로 문단 나누기)
 *   sum  요약 (한 줄씩)
 *   mn   암기 요령 [{ k: '머리글자', s: '문장 (**굵게**)', map: [['글자', '뜻'], ...] }]
 *   cards  떠올리기 카드 [['앞면', '뒷면'], ...]          (없어도 돼요)
 *   ox   O/X 문제 [['문장', true면 O / false면 X, '해설'], ...]  (배운 직후 바로 확인에 써요)
 *   kw   기출 자동 연결용 낱말 ['낱말', ...]               (없어도 돼요)
 *   why  왜 그럴까 (없어도 돼요) · note 참고 메모 (없어도 돼요) · fig 그림 안내 { q: '구글 검색어' } (없어도 돼요)
 *   v    나중에 추가한 내용이면 차수 (3 이상이면 앱에 '추가' 표시)
 *   flow 기전 흐름 ['원인', '변화', '결과'] (3단계 이상) → 카드에 화살표로 보이고 빈칸 문제가 저절로 생겨요 (없어도 돼요)
 *   en   영어 키워드 (RN 대비, 없어도 돼요)
 *   tm   의학용어 과목에 있는 영어 단어 ['necrosis', 'edema'] → 누르면 의학용어 카드가 열려요 (없어도 돼요)
 *
 * 문제 하나의 항목
 *   id 고유 이름 · c 관련 개념 id 목록(1~4개, 모두 배워야 문제가 열려요) · q 문제 · o 보기 5개
 *   a 정답 번호 (0부터: 첫 번째 보기 = 0) · k 묻는 것 · e 정답 이유 · x 보기별 이유 (정답 칸은 '')
 *   lv 2 = 국시 수준 · case: true = 사례형 · tag '우선순위', '부정형', '수치 해석' 등
 *
 * 따옴표(')와 쉼표(,)가 빠지면 과목이 열리지 않아요. 그럴 땐 첫 화면에 알림이 뜨고, 다른 과목은 그대로 쓸 수 있어요.
 */
NSA.subject({
  id: 'example-subject',
  title: '예시 과목',
  version: 1,
  units: [
    { id: 'u1', title: '첫 번째 단원', short: '첫 단원',
      concepts: [
        { id: 'u1c01', t: '첫 번째 개념', pr: 3,
          ex: '설명 첫 문단.\n설명 둘째 문단.',
          sum: ['요약 1', '요약 2'],
          mn: [{ k: '가·나·다', s: '**가**방에 **나**비가 **다**섯 마리', map: [['가', '가방'], ['나', '나비'], ['다', '다섯']] }],
          cards: [['앞면 질문', '뒷면 답']],
          ox: [['이 문장은 맞다.', true, '맞는 이유']],
          kw: ['핵심 낱말'] },
        { id: 'u1c02', t: '두 번째 개념', pr: 2,
          ex: '설명.',
          sum: ['요약'],
          mn: [{ k: '요령', s: '외우는 문장' }],
          ox: [['이 문장은 틀리다.', false, '틀린 이유']] }
      ],
      qs: [
        { id: 'u1-q1', c: ['u1c01'], lv: 1,
          q: '문제 내용은?',
          o: ['보기 1', '보기 2', '보기 3', '보기 4', '보기 5'], a: 0,
          k: '묻는 것', e: '정답 이유',
          x: ['', '2번이 틀린 이유', '3번이 틀린 이유', '4번이 틀린 이유', '5번이 틀린 이유'] }
      ]
    }
  ],
  /* 아래는 없어도 돼요 */
  tables: [ { id: 't1', u: 'u1', title: '표 제목', head: ['구분', 'A', 'B'], rows: [['항목', '값', '값']] } ],
  orders: [ { id: 'o1', u: 'u1', title: '순서 제목', items: ['첫째', '둘째', '셋째'], hint: '외우는 요령' } ],
  pairs: [ { u: 'u1', t: '헷갈리는 것', a: '왼쪽 설명', b: '오른쪽 설명' } ],
  numbers: [ { u: 'u1', k: '기준값 이름', v: '값' } ]
});
